using System.Runtime.CompilerServices;

namespace Dex.Domain.Risk;

/// <summary>
/// Perpetual / derivative position. All monetary values use System.Decimal (fixed-point).
/// Thread-safety: mutated only under RiskEngine lock or single-writer guarantee.
/// </summary>
public sealed class Position
{
    public long AccountId { get; }
    public int MarketId { get; }
    public MarginMode MarginMode { get; }
    public PositionSide Side { get; private set; }
    public decimal Quantity { get; private set; }          // absolute size
    public decimal EntryPrice { get; private set; }
    public decimal IsolatedMargin { get; private set; }    // only for Isolated mode
    public decimal RealizedPnl { get; private set; }
    public long LastUpdateTicks { get; private set; }

    public Position(long accountId, int marketId, MarginMode marginMode)
    {
        if (accountId <= 0) throw new ArgumentOutOfRangeException(nameof(accountId));
        if (marketId <= 0) throw new ArgumentOutOfRangeException(nameof(marketId));

        AccountId = accountId;
        MarketId = marketId;
        MarginMode = marginMode;
        Side = PositionSide.Flat;
        Quantity = 0m;
        EntryPrice = 0m;
        IsolatedMargin = 0m;
        RealizedPnl = 0m;
        LastUpdateTicks = DateTime.UtcNow.Ticks;
    }

    public bool IsOpen => Side != PositionSide.Flat && Quantity > 0m;

    /// <summary>
    /// Unrealized PnL at given mark price.
    /// Long:  (mark - entry) * qty
    /// Short: (entry - mark) * qty
    /// </summary>
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public decimal UnrealizedPnl(decimal markPrice)
    {
        if (!IsOpen || markPrice <= 0m) return 0m;

        return Side == PositionSide.Long
            ? (markPrice - EntryPrice) * Quantity
            : (EntryPrice - markPrice) * Quantity;
    }

    /// <summary>
    /// Applies a fill that increases or reduces the position.
    /// Returns realized PnL generated by this fill (for closing trades).
    /// </summary>
    public decimal ApplyFill(PositionSide fillSide, decimal fillQty, decimal fillPrice, decimal realizedPnlDelta)
    {
        if (fillQty <= 0m) throw new ArgumentOutOfRangeException(nameof(fillQty));
        if (fillPrice <= 0m) throw new ArgumentOutOfRangeException(nameof(fillPrice));

        if (!IsOpen)
        {
            // Opening
            Side = fillSide;
            Quantity = fillQty;
            EntryPrice = fillPrice;
            RealizedPnl += realizedPnlDelta;
            LastUpdateTicks = DateTime.UtcNow.Ticks;
            return realizedPnlDelta;
        }

        if (Side == fillSide)
        {
            // Increasing same side → weighted average entry
            var totalCost = EntryPrice * Quantity + fillPrice * fillQty;
            Quantity += fillQty;
            EntryPrice = totalCost / Quantity;
            RealizedPnl += realizedPnlDelta;
            LastUpdateTicks = DateTime.UtcNow.Ticks;
            return realizedPnlDelta;
        }

        // Opposite side → reducing / flipping
        if (fillQty < Quantity)
        {
            // Partial close
            var closedQty = fillQty;
            var pnl = Side == PositionSide.Long
                ? (fillPrice - EntryPrice) * closedQty
                : (EntryPrice - fillPrice) * closedQty;

            Quantity -= closedQty;
            RealizedPnl += pnl + realizedPnlDelta;
            LastUpdateTicks = DateTime.UtcNow.Ticks;
            return pnl + realizedPnlDelta;
        }

        if (fillQty == Quantity)
        {
            // Full close
            var pnl = Side == PositionSide.Long
                ? (fillPrice - EntryPrice) * Quantity
                : (EntryPrice - fillPrice) * Quantity;

            Side = PositionSide.Flat;
            Quantity = 0m;
            EntryPrice = 0m;
            RealizedPnl += pnl + realizedPnlDelta;
            LastUpdateTicks = DateTime.UtcNow.Ticks;
            return pnl + realizedPnlDelta;
        }

        // Flip
        var closeQty = Quantity;
        var closePnl = Side == PositionSide.Long
            ? (fillPrice - EntryPrice) * closeQty
            : (EntryPrice - fillPrice) * closeQty;

        var openQty = fillQty - closeQty;
        Side = fillSide;
        Quantity = openQty;
        EntryPrice = fillPrice;
        RealizedPnl += closePnl + realizedPnlDelta;
        LastUpdateTicks = DateTime.UtcNow.Ticks;
        return closePnl + realizedPnlDelta;
    }

    public void AddIsolatedMargin(decimal amount)
    {
        if (MarginMode != MarginMode.Isolated)
            throw new InvalidOperationException("AddIsolatedMargin is only valid for Isolated positions.");
        if (amount <= 0m) throw new ArgumentOutOfRangeException(nameof(amount));
        IsolatedMargin += amount;
        LastUpdateTicks = DateTime.UtcNow.Ticks;
    }

    public void RemoveIsolatedMargin(decimal amount)
    {
        if (MarginMode != MarginMode.Isolated)
            throw new InvalidOperationException("RemoveIsolatedMargin is only valid for Isolated positions.");
        if (amount <= 0m || amount > IsolatedMargin)
            throw new ArgumentOutOfRangeException(nameof(amount));
        IsolatedMargin -= amount;
        LastUpdateTicks = DateTime.UtcNow.Ticks;
    }
}
